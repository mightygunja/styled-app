/**
 * Writes functions/src/publicPhrases.ts: the piece phrases the logged-out
 * pages ask the live feed for.
 *
 * The public pages (guides, the public trend page) show real products for
 * their pieces. Anyone can load those pages, and a search costs a credit, so
 * the server needs to know which phrases a visitor without an account may
 * cause a search for: exactly the ones those pages can ask - the guides'
 * own pieces and the built-in trends' key pieces, per department - and
 * nothing a stranger types into a request.
 *
 * Re-run after any change to the guides' pieces, the catalogue rows they
 * point at, or the seed trends (auditChannel3Shelf fails until you do):
 *
 *   npx tsx scripts/buildPublicPhrases.ts
 */

import fs from 'fs';
import path from 'path';
import { GUIDE_PIECES } from '../src/data/guidePieces';
import { BALANCED_CATALOG } from '../src/data/mockProductCatalog';
import { SEED_TRENDS } from '../src/data/seedTrends';
import { railPhrases } from '../src/services/publicRealPieces';
import { trendAnchors } from '../src/services/trendSeeds';
import { keptQuery } from '../functions/src/channel3';

/** Key pieces per trend the public trend page looks up (PUBLIC_LIVE_PIECES in TrendsPublicScreen). */
export const PUBLIC_TREND_PIECES = 2;

export function publicPhrases(): { women: string[]; men: string[] } {
  const byId = new Map(BALANCED_CATALOG.map(p => [p.id, p]));
  const rows = (ids: string[]) => ids.map(id => byId.get(`p-${id}`)).filter((p): p is NonNullable<typeof p> => !!p);
  const women = new Set<string>();
  const men = new Set<string>();
  Object.values(GUIDE_PIECES).forEach(set => {
    railPhrases(rows(set.women)).forEach(p => women.add(p));
    railPhrases(rows(set.men)).forEach(p => men.add(p));
  });
  SEED_TRENDS.forEach(trend => {
    trendAnchors(trend, 'womens', PUBLIC_TREND_PIECES).forEach(p => women.add(p));
    trendAnchors(trend, 'mens', PUBLIC_TREND_PIECES).forEach(p => men.add(p));
  });
  // Stored exactly as the server will see them: it cleans every phrase it is
  // asked for (keptQuery) before comparing it with this list.
  const clean = (set: Set<string>) =>
    Array.from(new Set(Array.from(set).map(p => keptQuery(p)).filter((p): p is string => !!p))).sort();
  return { women: clean(women), men: clean(men) };
}

export function publicPhrasesSource(): string {
  const { women, men } = publicPhrases();
  const list = (items: string[]) => items.map(p => `  ${JSON.stringify(p)},`).join('\n');
  return `/**
 * GENERATED by scripts/buildPublicPhrases.ts - do not edit by hand.
 *
 * The piece phrases a visitor WITHOUT an account may cause a Channel3 search
 * for: the public guides' own pieces and the built-in trends' key pieces.
 * Any other phrase from an unsigned request is answered only from what is
 * already kept (see searchChannel3Kept).
 */

export const PUBLIC_PHRASES: Record<'women' | 'men', readonly string[]> = {
  women: [
${list(women)}
  ],
  men: [
${list(men)}
  ],
};
`;
}

if (require.main === module) {
  const file = path.join(__dirname, '..', 'functions', 'src', 'publicPhrases.ts');
  fs.writeFileSync(file, publicPhrasesSource());
  const { women, men } = publicPhrases();
  console.log(`Wrote ${path.relative(path.join(__dirname, '..'), file)}: ${women.length} women's phrases, ${men.length} men's.`);
}
