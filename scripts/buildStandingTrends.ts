/**
 * Writes functions/src/standingTrends.ts: the trends that ship inside the
 * app (src/data/seedTrends.ts), as the weekly review reads them.
 *
 *   npx tsx scripts/buildStandingTrends.ts
 *
 * The server cannot import the app's own files, so it gets this copy. Run it
 * after ANY change to the built-in trends - scripts/auditTrendReport.ts
 * fails while the copy is out of date.
 */

import fs from 'fs';
import path from 'path';
import { SEED_TRENDS } from '../src/data/seedTrends';

export function standingTrends(): Array<{ id: string; name: string; summary: string }> {
  return SEED_TRENDS.map(trend => ({
    id: trend.id,
    name: trend.name,
    summary: `${trend.summary} (${trend.season} ${trend.year}, ${trend.stage})`,
  }));
}

export function standingTrendsSource(): string {
  return `/**
 * GENERATED by scripts/buildStandingTrends.ts - do not edit by hand.
 *
 * The trends that ship inside the app, for the weekly review
 * (trendReport.ts: standingChanges).
 */
import { StandingTrend } from './trendReport';

export const STANDING_TRENDS: StandingTrend[] = [
${standingTrends()
  .map(t => `  { id: ${JSON.stringify(t.id)}, name: ${JSON.stringify(t.name)}, summary: ${JSON.stringify(t.summary)} },`)
  .join('\n')}
];
`;
}

if (require.main === module) {
  const file = path.join(__dirname, '..', 'functions', 'src', 'standingTrends.ts');
  fs.writeFileSync(file, standingTrendsSource());
  console.log(`Wrote ${path.relative(path.join(__dirname, '..'), file)}: ${standingTrends().length} standing trends.`);
}
